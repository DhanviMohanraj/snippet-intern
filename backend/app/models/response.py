"""Structured response domain models for grounded product recommendations.

Defines Pydantic models separating authoritative catalogue product data from generated
qualitative explanations, with strict validation for product IDs, prices, and specs.
"""

from __future__ import annotations

from typing import Any
from pydantic import BaseModel, ConfigDict, Field, field_validator

from app.models.product import Category


class ProductRecommendation(BaseModel):
    """Authoritative, validated product recommendation with grounded explanation."""

    model_config = ConfigDict(extra="forbid", validate_assignment=True)

    product_id: str = Field(description="Unique product identifier from catalogue (e.g. LAP-0001)")
    name: str = Field(description="Product display name from catalogue")
    brand: str = Field(description="Product brand from catalogue")
    category: Category = Field(description="Product category")
    price_inr: int = Field(gt=0, description="Authoritative catalogue price in INR")
    rating: float | None = Field(default=None, ge=0.0, le=5.0, description="Average review rating")
    verified_specs: dict[str, Any] = Field(
        default_factory=dict, description="Factual specifications directly copied from catalogue"
    )
    features: list[str] = Field(default_factory=list, description="Verified key product features")
    overall_score: float = Field(ge=0.0, le=100.0, description="Composite ranking score from Module 8 (0-100)")
    reasoning: str = Field(description="Concise explanation of why product fits the user's requirements")
    advantages: list[str] = Field(
        default_factory=list, description="Supported product strengths relevant to the user"
    )
    trade_offs: list[str] = Field(
        default_factory=list, description="Relevant limitations or trade-offs supported by product data"
    )
    match_explanation: str = Field(description="Explanation of constraints and preferences satisfied")
    limitations: list[str] = Field(
        default_factory=list, description="Missing or unverifiable catalogue information"
    )

    @field_validator("product_id", "name", "brand", "reasoning", "match_explanation")
    @classmethod
    def validate_non_empty_strings(cls, v: str, info: Any) -> str:
        if not isinstance(v, str) or not v.strip():
            raise ValueError(f"'{info.field_name}' must be a non-empty string.")
        return v.strip()


class RecommendationResponse(BaseModel):
    """Top-level structured recommendation response."""

    model_config = ConfigDict(extra="forbid", validate_assignment=True)

    message: str = Field(description="Introductory or summary message for the user")
    category: Category | None = Field(default=None, description="Product category recommended")
    recommendations: list[ProductRecommendation] = Field(
        default_factory=list,
        description="Ordered list of recommended products strictly preserving Module 8 ranking",
    )
    total_matching: int = Field(ge=0, description="Total eligible matching products from search")
    follow_up_question: str | None = Field(
        default=None, description="Optional follow-up question or clarification prompt"
    )
    data_quality_notes: list[str] = Field(
        default_factory=list, description="Notes on missing or unverifiable catalogue specifications"
    )
    is_fallback: bool = Field(
        default=False, description="Whether this response was generated via deterministic fallback"
    )
    fallback_reason: str | None = Field(
        default=None, description="Reason for fallback generation if applicable"
    )
    has_matches: bool = Field(default=True, description="Whether eligible recommendations were found")

    @field_validator("message")
    @classmethod
    def validate_message(cls, v: str) -> str:
        if not isinstance(v, str) or not v.strip():
            raise ValueError("'message' must be a non-empty string.")
        return v.strip()


class LLMProductExplanation(BaseModel):
    """Intermediate qualitative explanation generated by LLM for a single product."""

    model_config = ConfigDict(extra="forbid", validate_assignment=True)

    product_id: str = Field(description="Exact Product ID being explained")
    reasoning: str = Field(description="Tailored explanation for user's use cases and preferences")
    advantages: list[str] = Field(default_factory=list, description="Key strengths supported by product specs")
    trade_offs: list[str] = Field(default_factory=list, description="Honest trade-offs supported by product data")
    match_explanation: str = Field(
        default="", description="Explanation of requirements and constraints satisfied"
    )
    limitations: list[str] = Field(
        default_factory=list, description="Missing specifications or unverified requirements"
    )

    @field_validator("product_id", "reasoning")
    @classmethod
    def validate_non_empty_strings(cls, v: str, info: Any) -> str:
        if not isinstance(v, str) or not v.strip():
            raise ValueError(f"'{info.field_name}' must be a non-empty string.")
        return v.strip()

    @field_validator("match_explanation")
    @classmethod
    def validate_match_explanation(cls, v: str) -> str:
        return (v or "").strip()


class LLMRecommendationPayload(BaseModel):
    """Raw structured payload generated by Groq LLM."""

    model_config = ConfigDict(extra="forbid", validate_assignment=True)

    message: str = Field(description="Introductory summary message")
    explanations: list[LLMProductExplanation] = Field(
        default_factory=list, description="List of product explanations"
    )
    follow_up_question: str | None = Field(
        default=None, description="Optional natural follow-up question for the user"
    )

    @field_validator("message")
    @classmethod
    def validate_message(cls, v: str) -> str:
        if not isinstance(v, str) or not v.strip():
            raise ValueError("'message' must be a non-empty string.")
        return v.strip()
